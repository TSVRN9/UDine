#!/usr/bin/env python3
"""Writes lib/ui/letter_paths.dart: the outlines of W F H B in Oswald Bold at 1 em = 1.0, y down, origin at the baseline start.
Flutter has no text-to-path, and the varsity letter's gold fill needs a dashed stitch along the outline.
Run: PYTHONPATH=<dir with fontTools> python3 tool/gen_letters.py"""
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent

def table(name, file, label):
    f = TTFont(root / f"assets/fonts/{file}.ttf")
    gs, upm = f.getGlyphSet(), f["head"].unitsPerEm
    cmap = f.getBestCmap()

    def fmt(x, y): return f"{x / upm:.5f},{-y / upm:.5f}"

    out = [f"// {label}", f"const {name} = {{"]
    for ch in "WFHB":
        pen = DecomposingRecordingPen(gs)
        gs[cmap[ord(ch)]].draw(pen)
        d, cur = [], None
        for op, args in pen.value:
            if op == "moveTo": d.append("M" + fmt(*args[0])); cur = args[0]
            elif op == "lineTo": d.append("L" + fmt(*args[0])); cur = args[0]
            elif op == "qCurveTo":
                pts = list(args)
                if pts[-1] is None: raise SystemExit("closed all-off-curve contour not handled")
                offs, end = pts[:-1], pts[-1]
                for i, c in enumerate(offs):
                    tgt = end if i == len(offs) - 1 else ((c[0] + offs[i + 1][0]) / 2, (c[1] + offs[i + 1][1]) / 2)
                    d.append("Q" + fmt(*c) + "," + fmt(*tgt)); cur = tgt
            elif op in ("closePath", "endPath"): d.append("Z")
            else: raise SystemExit(f"unhandled {op}")
        out.append(f"  '{ch}': '{''.join(d)}',")
    out.append("};")
    return out

out = ["// GENERATED by tool/gen_letters.py: path commands per hall letter, in em units (y down, baseline 0).",
       "// Command string: M x,y  L x,y  Q cx,cy,x,y  Z"]
out += table("letterPaths", "Oswald_700Bold", "Oswald Bold: the band and header letter, the where-chip's")
out += table("letterPathsSemi", "Oswald_600SemiBold", "Oswald SemiBold: Search's 12 dp tile (M2 `.ht`, 600)")
(root / "lib/ui/letter_paths.dart").write_text("\n".join(out) + "\n")
