// tool/m2.json (a snapshot of the RN branch's design-tokens/m2.json, see sync_fixture.sh) -> lib/theme/m2_tokens.g.dart.
// `dart run tool/gen_tokens.dart` writes it; test/theme/tokens_currency_test.dart fails when the file on disk is not what
// `generate` prints. Stack-neutral JSON in; Dart names out. Every entry carries the JSON's `trace` (the M2 rule it comes from).
import 'dart:convert';
import 'dart:io';

String _cap(String s) => s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);
String _num(num v) => v is int ? '$v.0' : '$v';

String _color(String v) {
  final hex = RegExp(r'^#([0-9a-f]{6})$').firstMatch(v);
  if (hex != null) return 'Color(0xFF${hex[1]!.toUpperCase()})';
  final m = RegExp(r'^rgba?\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)$').firstMatch(v.replaceAll(' ', ''));
  if (m == null) throw FormatException('colour $v');
  return 'Color.fromRGBO(${m[1]}, ${m[2]}, ${m[3]}, ${m[4] ?? '1'})';
}

String _curve(dynamic e) {
  if (e == 'emphasized') return 'emphasized';
  if (e == 'linear') return 'Curves.linear';
  final c = (e as List).cast<num>();
  return 'Cubic(${c.map(_num).join(', ')})';
}

String generate(Map<String, dynamic> j, {String source = 'design-tokens/m2.json'}) {
  final trace = (j['trace'] as Map).cast<String, String>();
  // tokens only the React Native stack needs (no M2 rule behind them) are not generated
  final rnOnly = ((j['rnOnly'] ?? const []) as List).cast<String>().toSet();
  Iterable<MapEntry<String, dynamic>> own(String group, Map m) => m.entries.where((e) => !rnOnly.contains('$group.${e.key}')).map((e) => MapEntry(e.key as String, e.value));
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from tool/m2.json ($source). Do not edit: change the JSON and run `dart run tool/gen_tokens.dart`.')
    ..writeln("import 'package:flutter/animation.dart';")
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln("import 'kinds.dart';")
    ..writeln();
  String doc(String path, [String indent = '  ']) => trace.containsKey(path) ? '$indent/// ${trace[path]}\n' : '';
  void cls(String name, String group, Iterable<(String, String)> rows) {
    out.writeln('abstract final class $name {');
    for (final (path, line) in rows) {
      out.write(doc('$group.$path'));
      out.writeln('  $line');
    }
    out.writeln('}\n');
  }

  final color = (j['color'] as Map).cast<String, String>();
  cls('M2Color', 'color', [for (final e in own('color', color)) (e.key, 'static const ${e.key} = ${_color(e.value)};')]);

  final g = j['grade'] as Map;
  out.writeln('abstract final class M2Grade {');
  out.write(doc('grade.carbon'));
  out.writeln('  /// [tile, ink]');
  out.writeln('  static const carbon = {');
  for (final e in (g['carbon'] as Map).entries) {
    out.writeln("    '${e.key}': (${_color(e.value['tile'])}, ${_color(e.value['ink'])}),");
  }
  out.writeln('  };');
  out.write(doc('grade.health'));
  out.writeln('  static const health = [${(g['health']['tiles'] as List).map((c) => _color(c)).join(', ')}];');
  out.writeln('  static const healthInk = ${_color(g['health']['ink'])};');
  out.writeln('}\n');

  final font = (j['font'] as Map).cast<String, Map>();
  final metrics = j['fontMetrics'] as Map;
  String family(String f) => f.replaceAll(' ', '');
  const weights = {400: 'w400', 500: 'w500', 600: 'w600', 700: 'w700'};
  final type = (j['type'] as Map).cast<String, Map>();
  cls('M2Text', 'type', [
    for (final e in type.entries)
      (
        e.key,
        'static const ${e.key} = M2Type(${_num(e.value['size'])}, ${e.value['line'] == 'normal' ? 'null' : _num(e.value['line'])}, '
            "'${family(font[e.value['font']]!['family'])}', FontWeight.${weights[font[e.value['font']]!['weight']]}"
            '${e.value['tabular'] == true ? ', tabular: true' : ''});'
      ),
  ]);
  out.writeln('/// What `line-height: normal` is for each family: (ascender - descender + lineGap) / unitsPerEm of the shipped TTF.');
  out.writeln('abstract final class M2FontMetrics {');
  out.writeln('  static const normalLine = {${[for (final e in metrics.entries) "'${family(e.key)}': ${_num(e.value['normalLine'])}"].join(', ')}};');
  out.writeln('}\n');

  cls('M2Space', 'space', [for (final e in own('space', j['space'] as Map)) (e.key, 'static const ${e.key} = ${_num(e.value)};')]);
  cls('M2Radius', 'radius', [for (final e in (j['radius'] as Map).entries) (e.key, 'static const ${e.key} = ${_num(e.value)};')]);
  cls('M2Size', 'size', [
    for (final e in own('size', j['size'] as Map))
      (e.key, e.value is List ? 'static const ${e.key} = (${_num(e.value[0])}, ${_num(e.value[1])});' : 'static const ${e.key} = ${_num(e.value)};'),
  ]);
  cls('M2Opacity', 'opacity', [for (final e in (j['opacity'] as Map).entries) (e.key, 'static const ${e.key} = ${_num(e.value)};')]);
  cls('M2Collapse', 'collapse', [for (final e in (j['collapse'] as Map).entries) (e.key, 'static const ${e.key} = ${_num(e.value)};')]);
  cls('M2Edge', 'edge', [for (final e in (j['edge'] as Map).entries) (e.key, 'static const ${e.key} = ${_num(e.value)};')]);

  // gradients: colours and locations; `height` stays in the JSON for the screens' layout numbers
  out.writeln('abstract final class M2Gradient {');
  for (final e in (j['gradient'] as Map).entries) {
    final v = e.value as Map;
    out.write(doc('gradient.${e.key}'));
    out.writeln('  static const ${e.key} = (colors: [${(v['stops'] as List).map((c) => _color(c)).join(', ')}], stops: [${(v['locations'] as List).map((n) => _num(n)).join(', ')}]);');
  }
  out.writeln('}\n');

  out.writeln('abstract final class M2Shadow {');
  for (final e in (j['shadow'] as Map).entries) {
    out.write(doc('shadow.${e.key}'));
    out.writeln('  static const ${e.key} = [');
    for (final s in e.value as List) {
      out.writeln('    BoxShadow(offset: Offset(${_num(s['x'])}, ${_num(s['y'])}), blurRadius: ${_num(s['blur'])}, color: ${_color(s['color'])}),');
    }
    out.writeln('  ];');
  }
  out.writeln('}\n');

  out.writeln('/// The felt patches: corner radius, stitch inset, stitch radius, stitch width.');
  out.writeln('abstract final class M2Felt {');
  for (final e in (j['felt'] as Map).entries) {
    final v = e.value as Map;
    for (final f in ['radius', 'inset', 'stitchRadius', 'stitchWidth']) {
      out.writeln('  static const ${e.key}${_cap(f)} = ${_num(v[f])};');
    }
  }
  out.writeln('}\n');
  out.writeln('/// The chenille letter\'s text x in its 200 dp box, per hall.');
  out.writeln('const letterX = {${[for (final e in (j['letterX'] as Map).entries) "'${e.key}': ${_num(e.value)}"].join(', ')}};\n');

  final seg = (j['curves']['emphasized'] as List).map((s) => '[${(s as List).map((n) => _num(n)).join(', ')}]').join(', ');
  out.write(doc('curves.emphasized'));
  out.writeln('const emphasized = Emphasized([$seg]);\n');

  // motion: a map with `d` and `e` is an Anim; a lone `d` is `<name>D` in ms; a lone `e` is `<name>E`; every other leaf is a number
  final motion = StringBuffer();
  void walk(String name, dynamic v, String traceKey) {
    if (v is Map) {
      final hasD = v.containsKey('d'), hasE = v.containsKey('e');
      if (hasD && hasE) {
        motion.write(doc(traceKey));
        motion.writeln('  static const $name = Anim(${v['d']}, ${_curve(v['e'])});');
      }
      for (final e in v.entries) {
        if (e.key == 'd' && hasE) continue;
        if (e.key == 'e' && hasD) continue;
        if (e.key == 'd') {
          motion.write(doc(traceKey));
          motion.writeln('  static const ${name}D = ${e.value};');
        } else if (e.key == 'e') {
          motion.write(doc(traceKey));
          motion.writeln('  static const ${name}E = ${_curve(e.value)};');
        } else {
          walk('$name${_cap(e.key)}', e.value, traceKey);
        }
      }
    } else if (v is bool) {
      motion.writeln('  static const $name = $v;');
    } else {
      motion.write(doc(traceKey));
      motion.writeln('  static const $name = ${_num(v as num)};');
    }
  }

  for (final e in own('motion', j['motion'] as Map)) {
    walk(e.key, e.value, 'motion.${e.key}');
  }
  out.writeln('/// Durations are ms; every animation is an `Anim`, a duration with its curve.');
  out.writeln('abstract final class M2Motion {');
  out.write(motion);
  out.writeln('}');
  return out.toString();
}

void main(List<String> args) {
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final json = jsonDecode(File('$root/tool/m2.json').readAsStringSync()) as Map<String, dynamic>;
  File('$root/lib/theme/m2_tokens.g.dart').writeAsStringSync(generate(json));
  stdout.writeln('wrote lib/theme/m2_tokens.g.dart');
}
