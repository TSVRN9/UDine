#!/usr/bin/env node
// design-tokens/m2.json -> src/lib/m2.generated.ts (`m2` for theme.ts, `m2MotionData` and `m2Curves` for motion.ts).
// Stack-neutral JSON in; React Native names and resolved pixel line heights out. `pnpm tokens` writes it, and
// src/lib/m2.generated.test.ts fails when the file on disk is not what this prints.
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "../../design-tokens/m2.json");
const OUT = path.join(__dirname, "../src/lib/m2.generated.ts");
const WEIGHT = { 400: "Regular", 500: "Medium", 600: "SemiBold", 700: "Bold" };
const HANDLED = new Set(["$comment", "version", "rnOnly", "trace", "color", "grade", "font", "fontMetrics", "type", "motion", "curves"]);
const r1 = (x) => Math.round(x * 10) / 10;

const rnFont = ({ family, weight }) => `${family.replace(/ /g, "")}_${weight}${WEIGHT[weight]}`;

function build(j) {
  const font = Object.fromEntries(Object.entries(j.font).map(([k, f]) => [k, rnFont(f)]));
  const type = Object.fromEntries(
    Object.entries(j.type).map(([k, t]) => {
      const f = j.font[t.font];
      const line = t.line === "normal" ? r1(t.size * j.fontMetrics[f.family].normalLine) : t.line;
      return [k, { size: t.size, line, font: font[t.font], tabular: !!t.tabular }];
    }),
  );
  const color = {
    ...j.color,
    carbon: Object.fromEntries(Object.entries(j.grade.carbon).map(([k, v]) => [k, [v.tile, v.ink]])),
    health: j.grade.health.tiles,
    healthInk: j.grade.health.ink,
  };
  // every other group (space, radius, size, felt, ...) passes through as it is
  const rest = Object.fromEntries(Object.entries(j).filter(([k]) => !HANDLED.has(k)));
  const m2 = { color, font, type, ...rest };
  return { m2, m2MotionData: j.motion, m2Curves: j.curves };
}

const lit = (v) => JSON.stringify(v, null, 2).replace(/"([A-Za-z_]\w*)":/g, "$1:");

function generate(json) {
  const o = build(json);
  return [
    "// GENERATED by mobile/scripts/gen-tokens.js from design-tokens/m2.json. Do not edit: change the JSON and run `pnpm tokens`.",
    `export const m2 = ${lit(o.m2)} as const;`,
    `export const m2MotionData = ${lit(o.m2MotionData)} as const;`,
    `export const m2Curves = ${lit(o.m2Curves)} as const;`,
    "",
  ].join("\n");
}

module.exports = { generate, SRC, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, generate(JSON.parse(fs.readFileSync(SRC, "utf8"))));
  console.log("wrote", path.relative(process.cwd(), OUT));
}
